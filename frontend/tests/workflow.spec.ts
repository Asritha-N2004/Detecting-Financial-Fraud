import {test,expect} from '@playwright/test';
test('register, assess synthetic evidence, inspect all analysis pages',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'New here? Create a workspace'}).click();
 await page.getByLabel('Organization').fill('Browser test workspace');
 await page.getByLabel('Email').fill(`browser-${Date.now()}@example.com`);
 await page.getByLabel('Password',{exact:true}).fill('browser-test-password-2026');
 await page.getByRole('button',{name:'Create workspace',exact:true}).click();
 await expect(page.getByRole('heading',{name:/A clearer view/})).toBeVisible();
 await page.getByRole('button',{name:/01.*Aster Manufacturing/}).click();
 await expect(page.getByRole('heading',{name:'Risk analysis',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Quantitative indicators'})).toBeVisible({timeout:30000});
 await expect(page.getByRole('heading',{name:'Portfolio covariance & diversification'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Debt maturity & funding gaps'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Overlapping risk & weight sensitivity'})).toBeVisible();
 const savedScore=await page.locator('.analysis-hero .score-number').innerText();
 await page.getByLabel('credit weight (%)').fill('20');
 await expect(page.getByRole('button',{name:'Explore weights'})).toBeDisabled();
 await page.getByLabel('market weight (%)').fill('30');
 const diagnostic=page.waitForResponse(r=>r.url().endsWith('/sensitivity')&&r.request().method()==='POST'&&r.status()===200);
 await page.getByRole('button',{name:'Explore weights'}).click();
 expect((await (await diagnostic).json()).exploratory).toBe(true);
 await expect(page.locator('.analysis-hero .score-number')).toHaveText(savedScore);
 await expect(page.getByText(/No comparable dimension-score history supplied/)).toBeVisible();
 await page.getByRole('button',{name:'Reset to saved weights'}).click();
 await expect(page.getByLabel('credit weight (%)')).toHaveValue('25');
 await page.getByRole('heading',{name:'Overlapping risk & weight sensitivity'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'test-results/sensitivity-desktop.png'});
 await expect(page.getByRole('status')).toContainText('Durable job:');
 await expect(page.getByRole('status')).toContainText('succeeded',{timeout:10000});
 await page.screenshot({path:'test-results/analysis-desktop.png',fullPage:true});
 for(const name of ['Agent activity','Reflection explorer','Decision explanation','Audit history']){
   await page.getByRole('link',{name,exact:false}).first().click();
   await expect(page.locator('main')).not.toContainText('Workflow in progress');
 }
 await page.getByRole('link',{name:'Stress testing'}).click();
 await page.getByRole('button',{name:'Run stress test',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Hypothetical impact'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Cash timing / baseline and adverse'})).toBeVisible();
 await expect(page.locator('.recharts-line-curve')).toHaveCount(2);
 await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption('combined_adverse');
 await page.getByRole('button',{name:'Run stress test',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('A positive year-end cash balance does not fund an earlier deficit');
 await page.screenshot({path:'test-results/stress-desktop.png',fullPage:true});
 await page.getByRole('link',{name:'Overview',exact:true}).click();
 await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
 await expect(page.getByRole('heading',{name:/A clearer view/})).toBeVisible();
});

test('imports complete evidence and discloses synthetic empirical score correlations',async({page})=>{
 const {fileURLToPath}=await import('node:url');
 const bundle=fileURLToPath(new URL('../../data/synthetic/sensitivity_history.json',import.meta.url));
 await page.goto('/');
 await page.getByRole('button',{name:'New here? Create a workspace'}).click();
 await page.getByLabel('Organization').fill('History browser workspace');
 await page.getByLabel('Email').fill(`history-${Date.now()}@example.com`);
 await page.getByLabel('Password',{exact:true}).fill('history-browser-test-password');
 await page.getByRole('button',{name:'Create workspace',exact:true}).click();
 await page.getByRole('navigation').getByRole('link',{name:'New assessment',exact:true}).click();
 await page.getByLabel('Complete assessment JSON').setInputFiles(bundle);
 await page.getByRole('button',{name:'Import bundle and run'}).click();
 await expect(page.getByRole('heading',{name:'Quantitative indicators'})).toBeVisible({timeout:30000});
 await expect(page.getByText(/60 complete observations/)).toBeVisible();
 await expect(page.getByText('Constant score dimensions have undefined correlations')).toBeVisible();
 await expect(page.getByText('Synthetic history: demonstration correlations only, not measured company evidence')).toBeVisible();
 await page.getByRole('heading',{name:'Empirical score correlation'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'test-results/sensitivity-history.png'});
});
